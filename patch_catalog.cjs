const typeList = ["scientific_task", "core_singularity"];

const nodes = [];
for (let i = 0; i < realProblems.length; i++) {
  const p = realProblems[i];
  
  let z = "math";
  if (i >= 30) z = "physics";
  if (i >= 55) z = "informatics";
  if (i >= 75) z = "medicine";
  if (i >= 90) z = (i % 2 === 0) ? "economics" : "ethics";

  nodes.push({
    id: "real-catalog-" + i,
    title: p.t,
    description: p.d,
    state: "unresolved",
    type: typeList[Math.floor(Math.random() * 2)],
    targetFunction: "Formalize(" + p.t.replace(/[\s—-]+/g, "") + ")",
    zoneIds: [z],
    dependencyIds: [],
    dependentIds: [],
    fractalDepth: 1,
    economic: {
      costUnresolved: Math.floor(Math.random() * 1000) * 1000000 + 1000000,
      costToSolve: Math.floor(Math.random() * 100) * 100000 + 100000,
      marketGain: Math.floor(Math.random() * 2000) * 1000000 + 1000000,
      riskLoss: Math.floor(Math.random() * 5000) * 1000000 + 1000000
    },
    rewardClass: "reputation",
    prizeNote: "Catalog discovery",
    singularityHint: p.hint
  });
}

// Add simple deterministic dependency structure
for (let i = 1; i < nodes.length; i++) {
  // 30% chance to have a dependency on a node from same zone
  if (Math.random() < 0.3) {
      let parentIdx = i - 1;
      while (parentIdx > 0 && nodes[parentIdx].zoneIds[0] !== nodes[i].zoneIds[0]) {
          parentIdx--;
      }
      if (parentIdx >= 0 && nodes[parentIdx].zoneIds[0] === nodes[i].zoneIds[0]) {
          nodes[i].dependencyIds.push(nodes[parentIdx].id);
          nodes[parentIdx].dependentIds.push(nodes[i].id);
      }
  }
}

